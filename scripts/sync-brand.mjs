// Regenerates js/brand-tokens.js from tbj-brand's generated tokens.css, so every bot's status page and
// any page that imports BRAND_CSS picks up brand changes on the next fan-out.
//   node scripts/sync-brand.mjs                 (fetch from GitHub, tbj-brand main)
//   node scripts/sync-brand.mjs <path/to/tokens.css>
import { readFile, writeFile } from 'node:fs/promises';

const SRC = 'https://raw.githubusercontent.com/TheBooleanJulian/tbj-brand/main/dist/tokens.css';
const arg = process.argv[2];
const css = arg ? await readFile(arg, 'utf8') : await (await fetch(SRC)).text();
if (!css.includes('--cyan')) throw new Error('that does not look like tbj-brand tokens.css');

const out = `// Generated by scripts/sync-brand.mjs from tbj-brand dist/tokens.css. Do not edit.
export const BRAND_CSS = ${JSON.stringify(css.trim())};
`;
await writeFile(new URL('../js/brand-tokens.js', import.meta.url), out);
console.log(`js/brand-tokens.js: ${css.length} bytes of tokens`);
